import { cp, mkdir, readFile, rm, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { publishThumbnails, thumbnailHead } from "./family-thumbnail.mjs";
import { embedBuilderModule, renderPage } from "./pages.mjs";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const site = join(root, "site");
const marker = join(site, ".fuda-generated");
try {
  await readFile(marker);
  await rm(site, { recursive: true });
} catch (error) {
  if (error.code !== "ENOENT") throw error;
  // Never overwrite an existing directory that this script did not generate.
  try {
    await mkdir(site);
  } catch (mkdirError) {
    if (mkdirError.code === "EEXIST")
      throw new Error("site/ already exists and is not a generated Fuda site. Move it before building.");
    throw mkdirError;
  }
}
await mkdir(site, { recursive: true });
await writeFile(marker, "Generated by scripts/site.mjs\n");
for (const path of ["rocket.svg", "assets", "demo", "dist"]) {
  await cp(join(root, path), join(site, path), { recursive: true });
}
// The Card Studio and the Builder, from their templates with the family's header and footer, and the family's builder as a module for the browser.
// The two page templates are in demo/ for the build, and the pages they make are in the site's root.
await rm(join(site, "demo", "index.html"));
await rm(join(site, "demo", "builder.html"));
const pkg = JSON.parse(await readFile(join(root, "package.json"), "utf8"));
const ALT =
  "Fuda Cards: three collectible cards, classic gold, silver sport and cosmic violet, framing the same rocket picture.";
const thumbnails = thumbnailHead(pkg, { alt: ALT });
await writeFile(join(site, "index.html"), renderPage("index", thumbnails));
await writeFile(join(site, "builder.html"), renderPage("builder", thumbnails));
await writeFile(join(site, "demo", "family-embed-builder.js"), embedBuilderModule());
// The family's card, dark card and icon, at thumbnail.png, thumbnail-dark.png and icon.png beside the demo.
publishThumbnails(root, site);
await cp(
  join(root, "node_modules/@johnmorrisdotca/kazoku-ui/dist"),
  join(site, "node_modules/@johnmorrisdotca/kazoku-ui/dist"),
  { recursive: true },
);
// What demo/live-3d.html loads on demand: three.js and the rockets it shows, and nothing else of those packages.
for (const file of [
  "three/build/three.module.js",
  "three/build/three.core.js",
  "three/examples/jsm/loaders/GLTFLoader.js",
  "three/examples/jsm/utils/BufferGeometryUtils.js",
  "three/examples/jsm/utils/SkeletonUtils.js",
]) {
  await cp(join(root, "node_modules", file), join(site, "node_modules", file));
}
for (const rocket of [
  "starship-v3",
  "starship-v2",
  "starship-v1",
  "falcon-9-block-5",
  "falcon-9-ft",
  "falcon-heavy-falcon-heavy",
  "dragon-dragon-2-capsule",
  "dragon-dragon-1-capsule",
]) {
  for (const ending of [".glb", ".painted.svg"])
    await cp(
      join(root, "node_modules/@johnmorrisdotca/uchusen-rockets/dist/assets", rocket + ending),
      join(site, "node_modules/@johnmorrisdotca/uchusen-rockets/dist/assets", rocket + ending),
    );
}
await writeFile(join(site, ".nojekyll"), "");
console.log("site/ is ready");
