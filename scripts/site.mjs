import {cp, mkdir, readFile, rm, writeFile} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import {dirname, join} from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const site = join(root, 'site');
const marker = join(site, '.fuda-generated');
try {
  await readFile(marker);
  await rm(site, {recursive: true});
} catch (error) {
  if (error.code !== 'ENOENT') throw error;
  // Never overwrite an existing directory that this script did not generate.
  try { await mkdir(site); } catch (mkdirError) {
    if (mkdirError.code === 'EEXIST') throw new Error('site/ already exists and is not a generated Fuda site. Move it before building.');
    throw mkdirError;
  }
}
await mkdir(site, {recursive: true});
await writeFile(marker, 'Generated by scripts/site.mjs\n');
for (const path of ['index.html', 'rocket.svg', 'assets', 'demo', 'dist']) {
  await cp(join(root, path), join(site, path), {recursive: true});
}
await cp(join(root, 'node_modules/@johnmorrisdotca/kazoku-ui/dist'), join(site, 'node_modules/@johnmorrisdotca/kazoku-ui/dist'), {recursive: true});
await writeFile(join(site, '.nojekyll'), '');
console.log('site/ is ready');
